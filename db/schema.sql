-- =============================================================================
-- Mushroom Identifiers — PostgreSQL schema (self-hosted, no Supabase)
-- =============================================================================
-- Applied on every container start by scripts/migrate.mjs, so every statement
-- must be idempotent (IF NOT EXISTS / CREATE OR REPLACE / DO blocks).
--
--   A. Better Auth tables (user / session / account / verification)
--   B. Application tables — same columns, types and defaults as the live
--      Supabase project (generated from its schema on 2026-10-25)
--   C. Constraints, indexes, updated_at triggers, seed rows
-- =============================================================================

