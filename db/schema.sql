CREATE INDEX IF NOT EXISTS account_user_idx ON "account" ("userId");
CREATE UNIQUE INDEX IF NOT EXISTS account_provider_uidx ON "account" ("providerId", "accountId");

CREATE TABLE IF NOT EXISTS "verification" (
  "id"         text        PRIMARY KEY,
